export type EditorTranslationKey = keyof typeof EDITOR_MESSAGES.zh;
export type EditorTranslate = (key: EditorTranslationKey, values?: Record<string, string | number>) => string;

export function translate(locale: EditorLocale, key: EditorTranslationKey, values?: Record<string, string | number>) {
  let message: string = EDITOR_MESSAGES[locale][key] || EDITOR_MESSAGES.zh[key];
  for (const [name, value] of Object.entries(values || {})) {
    message = message.replaceAll(`{{${name}}}`, String(value));
  }
  return message;
}
